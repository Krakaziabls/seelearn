  /**
   * Ensures that the 'SeeLearn Examples' directory and initial files exist.
   * Recreates the cheatsheet or demo notes if deleted.
   */
  public static async ensureOnboardingAssets(app: App): Promise<TFile> {
    const { vault } = app;

    // 1. Ensure folder exists
    const existingFolder = vault.getAbstractFileByPath(OnboardingManager.EXAMPLES_DIR);
    if (!existingFolder) {
      try {
        await vault.createFolder(OnboardingManager.EXAMPLES_DIR);
      } catch {
        // Folder may have been created concurrently
      }
    }

    // 2. Ensure both cheatsheets exist (Syntax & Methodology)
    let syntaxFile = vault.getAbstractFileByPath(OnboardingManager.CHEATSHEET_SYNTAX_FILE);
    if (!isTFile(syntaxFile)) {
      try {
        syntaxFile = await vault.create(
          OnboardingManager.CHEATSHEET_SYNTAX_FILE,
          OnboardingManager.getSyntaxCheatsheetContent()
        );
      } catch {
        syntaxFile = vault.getAbstractFileByPath(OnboardingManager.CHEATSHEET_SYNTAX_FILE);
      }
    }

    let methodologyFile = vault.getAbstractFileByPath(OnboardingManager.CHEATSHEET_METHODOLOGY_FILE);
    if (!isTFile(methodologyFile)) {
      try {
        methodologyFile = await vault.create(
          OnboardingManager.CHEATSHEET_METHODOLOGY_FILE,
          OnboardingManager.getMethodologyCheatsheetContent()
        );
      } catch {
        methodologyFile = vault.getAbstractFileByPath(OnboardingManager.CHEATSHEET_METHODOLOGY_FILE);
      }
    }

    // 3. Clean up legacy single cheatsheet file if present
    const legacyCheatsheet = vault.getAbstractFileByPath(OnboardingManager.LEGACY_CHEATSHEET_FILE);
    if (isTFile(legacyCheatsheet)) {
      try {
        await vault.delete(legacyCheatsheet);
      } catch {
        // Ignore
      }
    }

    // 4. Clean up legacy unnumbered demo notes if present
    const legacyPaths = [
      'SeeLearn Examples/Пример — Биология клетки.md',
      'SeeLearn Examples/Пример — Столицы и Факты.md',
    ];
    for (const legacyPath of legacyPaths) {
      const legacyFile = vault.getAbstractFileByPath(legacyPath);
      if (isTFile(legacyFile)) {
        try {
          await vault.delete(legacyFile);
        } catch {
          // Ignore
        }
      }
    }

    // 5. Ensure all 5 comprehensive demo notes exist
    for (const demo of OnboardingManager.DEMO_NOTES) {
      const existing = vault.getAbstractFileByPath(demo.path);
      if (!isTFile(existing)) {
        try {
          await vault.create(demo.path, demo.getContent());
        } catch {
          // Ignore if created concurrently
        }
      }
    }

    return syntaxFile as TFile;
  }

  /**
   * Opens the requested cheatsheet note in an editor tab.
   * Defaults to 'syntax' cheatsheet.
   * If the cheatsheet is already open in a workspace leaf, activates and focuses that leaf.
   * If the file is missing, recreates it automatically before opening.
   */
  public static async openCheatsheetNote(
    app: App,
    type: 'syntax' | 'methodology' = 'syntax',
    forceUpdate = true
  ): Promise<void> {
    await OnboardingManager.ensureOnboardingAssets(app);

    const targetPath =
      type === 'methodology'
        ? OnboardingManager.CHEATSHEET_METHODOLOGY_FILE
        : OnboardingManager.CHEATSHEET_SYNTAX_FILE;
    const targetContent =
      type === 'methodology'
        ? OnboardingManager.getMethodologyCheatsheetContent()
        : OnboardingManager.getSyntaxCheatsheetContent();

    let targetFile = app.vault.getAbstractFileByPath(targetPath);
    if (!isTFile(targetFile)) {
      try {
        targetFile = await app.vault.create(targetPath, targetContent);
      } catch {
        targetFile = app.vault.getAbstractFileByPath(targetPath);
      }
    }
    if (!isTFile(targetFile)) return;

    if (forceUpdate && typeof (app.vault as any).modify === 'function') {
      try {
        await (app.vault as any).modify(targetFile, targetContent);
      } catch {
        // Ignore if failed to modify
      }
    }

    // Check if an existing markdown leaf already has this cheatsheet open
    const markdownLeaves = app.workspace.getLeavesOfType('markdown');
    for (const leaf of markdownLeaves) {
      const view = leaf.view;
      if (view && 'file' in view && (view as any).file?.path === targetPath) {
        app.workspace.setActiveLeaf(leaf, { focus: true });
        return;
      }
    }

    // Otherwise, open in a new workspace tab
    const leaf = app.workspace.getLeaf('tab');
    await leaf.openFile(targetFile);
    app.workspace.setActiveLeaf(leaf, { focus: true });
  }
